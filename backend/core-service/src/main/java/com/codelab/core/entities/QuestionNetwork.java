package com.codelab.core.entities;

import jakarta.persistence.*;
import lombok.Getter;
import lombok.Setter;

@Getter
@Setter
@Entity
public class QuestionNetwork {
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    public Long id;

    @Column(length = 3000, nullable = false)
    private String title;

    @Column(columnDefinition = "json", nullable = false)
    private String scenery;

    @Column(columnDefinition = "json", nullable = false)
    private String sceneryAnswers;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private QuestionTypeNetwork type;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private QuestionTopicNetwork topic;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false)
    private QuestionDifficultyNetwork difficulty;

    public enum QuestionTypeNetwork {
        MULTIPLE_CHOICE,
        PRACTICE
    }

    public enum QuestionTopicNetwork {
        BASIC_NETWORKING
    }

    public enum QuestionDifficultyNetwork {
        EASY,
        MEDIUM,
        HARD
    }
}


